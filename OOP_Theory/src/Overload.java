public class Overload {

    void add(int a, int b)
    {
        System.out.println("From Overload class a+b: "+(a+b));
    }

    void add(int a,int b,int c)
    {
        System.out.println("From Overload class a+b+c: "+(a+b+c));
    }

    void add(double a, double b)
    {
        System.out.println("From Overload class double a+b: "+(a+b));
    }


}
